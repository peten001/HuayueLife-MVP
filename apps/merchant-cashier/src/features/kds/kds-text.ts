export type KdsTextKey = keyof typeof text;
export function kdsText(locale: Locale, key: KdsTextKey) { return text[key][locale === 'vi' ? 1 : locale === 'en' ? 2 : 0]; }
export function kdsRequestKey() {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  return `kds-${Array.from(bytes, value => value.toString(16).padStart(2, '0')).join('')}`;
}
